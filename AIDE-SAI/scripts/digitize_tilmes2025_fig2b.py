"""Digitise Tilmes et al. (2025) Fig. 2b: yearly SO2 injection rate (Tg SO2/yr).

Input:  AIDE-SAI/data/tilmes2025/acp-25-6001-2025-f02-web.png (fetch_tilmes2025_fig2.sh).
Output: AIDE-SAI/validation_results/injection_rates/tilmes2025_fig2b.{csv,png}.

Curves (caption: "15N and 15S (green), 30N and 30S (red), total (black); different lines
indicate two ensemble members"). Red and green are the rate AT EACH of the two sites of a
pair, not the pair sum: while green is zero (2030-2032) red is half of black.

The curves are polylines with one vertex per year at the integer-year tick (kinks and
member divergences fall on integer years), so year Y's rate is read AT x = Y, not averaged
over [Y, Y+1) (that average is about the mean of the Y and Y+1 rates; 2026-11-25 review).

Method: pixel colour masks per curve; in each pixel column the curve pixels split into
clusters (one per resolved ensemble member; members that overlap give one cluster); the
column value is the mean of the cluster centres. Year Y's value is that column value
interpolated linearly to x(Y) between the two bracketing columns; lo/hi are the lowest and
highest cluster centre in those two columns (member spread where members are resolved).
Axis calibration was read off the tick marks by hand (constants below); read error about
0.3 Tg/yr.
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data/tilmes2025/acp-25-6001-2025-f02-web.png"
OUT = ROOT / "validation_results/injection_rates"

# Axis calibration (pixels of the web PNG): x 2020 -> 1218, 2040 -> 1372; y 5 -> 514.5, 25 -> 154.
X0, X_PER_YR = 1218, (1372 - 1218) / 20
Y_ZERO, Y_PER_TG = 604.6, (514.5 - 154) / 20
ROWS = (66, 603)                    # plot area, top to the zero line
COLS = (1222, 1830)
LEGEND = (slice(66, 240), slice(1180, 1360))
YEARS = range(2020, 2046)


def x2yr(x):
    return 2020 + (x - X0) / X_PER_YR


def y2tg(y):
    return (Y_ZERO - y) / Y_PER_TG


def main():
    a = np.rint(plt.imread(SRC)[..., :3] * 255).astype(int)
    R, G, B = a[..., 0], a[..., 1], a[..., 2]
    masks = {"tg_each_30deg": (R > 180) & (G < 90) & (B < 90),
             "tg_each_15deg": (G > 150) & (R < 150) & (B < 120),
             "tg_total": (R < 70) & (G < 70) & (B < 70)}
    series = {}
    for k, m in masks.items():
        m[LEGEND] = False
        col = {}
        for x in range(*COLS):
            ys = np.where(m[ROWS[0]:ROWS[1], x])[0] + ROWS[0]
            if len(ys):
                clusters = np.split(ys, np.where(np.diff(ys) > 3)[0] + 1)
                col[x] = [y2tg(c.mean()) for c in clusters]
        series[k] = {}
        for y in YEARS:
            xf = X0 + (y - 2020) * X_PER_YR
            x0, x1 = int(np.floor(xf)), int(np.floor(xf)) + 1
            if x0 in col and x1 in col:
                w = xf - x0
                vals = col[x0] + col[x1]
                series[k][y] = ((1 - w) * np.mean(col[x0]) + w * np.mean(col[x1]), min(vals), max(vals))

    OUT.mkdir(parents=True, exist_ok=True)
    keys = list(masks)
    with open(OUT / "tilmes2025_fig2b.csv", "w") as f:
        f.write("# Yearly SO2 injection rate (Tg SO2/yr), CCMI-2022 SSP2-4.5 SAI, CESM2-WACCM6,\n"
                "# digitised from Tilmes et al. (2025), ACP 25, 6001-6023, Fig. 2b (CC BY 4.0).\n"
                "# Generated by AIDE-SAI/scripts/digitize_tilmes2025_fig2b.py; do not edit.\n"
                "# tg_each_30deg / tg_each_15deg: rate at EACH of 30N and 30S / 15N and 15S (red / green);\n"
                "# tg_total: all four sites (black). <k>: member-mean curve read at the integer-year tick\n"
                "# (one vertex per year); <k>_lo/_hi: lowest/highest member at the tick (equal to <k>\n"
                "# within 0.1 where the two members overlap and are not resolved).\n"
                "# Empty: no curve pixels at the tick (rate 0 sits on the axis line).\n")
        f.write("year," + ",".join(f"{k},{k}_lo,{k}_hi" for k in keys) + "\n")
        for y in YEARS:
            cells = [",".join(f"{v:.2f}" for v in series[k][y]) if y in series[k] else ",," for k in keys]
            f.write(f"{y}," + ",".join(cells) + "\n")

    # Check figure: digitised yearly values drawn on the source panel.
    fig, ax = plt.subplots(figsize=(7, 5))
    x_lo, x_hi = 2020, x2yr(COLS[1])
    ax.imshow(a[ROWS[0]:ROWS[1] + 5, X0:COLS[1]].astype(np.uint8),
              extent=(x_lo, x_hi, y2tg(ROWS[1] + 5), y2tg(ROWS[0])), aspect="auto", alpha=0.6)
    for k, c in zip(keys, ("tab:red", "tab:green", "k")):
        yrs = [y for y in YEARS if y in series[k]]
        ax.errorbar(yrs, [series[k][y][0] for y in yrs],
                    yerr=[[series[k][y][0] - series[k][y][1] for y in yrs],
                          [series[k][y][2] - series[k][y][0] for y in yrs]],
                    fmt="o", ms=3, color=c, mec="w", mew=0.5, label=k)
    ax.axvspan(2029.5, 2032.5, color="tab:blue", alpha=0.08, label="AIDE-SAI run years 2030-2032")
    ax.set(xlim=(2019, 2046), ylim=(0, 25), xlabel="year", ylabel="Tg SO2 / yr",
           title="Tilmes et al. (2025) Fig. 2b, digitised at the integer-year ticks")
    ax.legend(fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(OUT / "tilmes2025_fig2b.png", dpi=120, metadata={"Software": None})
    print((OUT / "tilmes2025_fig2b.csv").read_text())


if __name__ == "__main__":
    main()
